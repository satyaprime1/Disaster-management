from pathlib import Path
import json
import numpy as np
import rasterio
from rasterio.transform import xy
from rasterio.warp import transform
from scipy import ndimage


def load_satellite_georeference():
    """
    Read CRS + transform from the Sentinel-2 reference raster.
    """

    metadata_dir = (
        Path(__file__).resolve().parent.parent
        / "data"
        / "satellite"
        / "metadata"
    )

    candidates = list(metadata_dir.glob("*.json"))

    if not candidates:
        raise FileNotFoundError(
            f"No satellite metadata found in {metadata_dir}"
        )

    metadata_file = max(
        candidates,
        key=lambda p: p.stat().st_mtime
    )

    with open(metadata_file, "r", encoding="utf-8") as f:
        metadata = json.load(f)

    return metadata


def get_geotransform_from_metadata(metadata):
    """
    Extract CRS and transform information.
    Supports metadata generated by satellite_input.py.
    """

    transform_data = metadata.get("transform")

    crs = metadata.get("crs")

    if not transform_data or not crs:
        raise ValueError(
            "Satellite metadata does not contain CRS/transform."
        )

    if isinstance(transform_data, dict):
        transform_values = (
            transform_data.get("a"),
            transform_data.get("b"),
            transform_data.get("c"),
            transform_data.get("d"),
            transform_data.get("e"),
            transform_data.get("f"),
        )

        transform_obj = rasterio.Affine(*transform_values)

    elif isinstance(transform_data, list):
        transform_obj = rasterio.Affine(*transform_data)

    else:
        raise ValueError(
            "Unsupported transform format."
        )

    return crs, transform_obj


def pixel_to_latlon(row, col, crs, transform_obj):
    """
    Convert raster row/column to WGS84 latitude/longitude.
    """

    x, y = xy(
        transform_obj,
        row,
        col,
        offset="center"
    )

    lon, lat = transform(
        crs,
        "EPSG:4326",
        [x],
        [y]
    )

    return float(lat[0]), float(lon[0])


def probability_to_regions(
    probability_map,
    threshold=0.5,
    min_pixels=20,
    max_regions=100
):
    """
    Convert probability map into connected geographic regions.

    Returns pixel regions first.
    """

    mask = probability_map >= threshold

    if not np.any(mask):
        return []

    structure = ndimage.generate_binary_structure(
        2,
        2
    )

    labels, number = ndimage.label(
        mask,
        structure=structure
    )

    regions = []

    for region_id in range(1, number + 1):

        rows, cols = np.where(
            labels == region_id
        )

        pixel_count = len(rows)

        if pixel_count < min_pixels:
            continue

        probabilities = probability_map[
            rows,
            cols
        ]

        center_row = float(np.mean(rows))
        center_col = float(np.mean(cols))

        regions.append({
            "region_id": int(region_id),
            "rows": rows,
            "cols": cols,
            "pixel_count": int(pixel_count),
            "center_row": center_row,
            "center_col": center_col,
            "max_probability": float(
                np.max(probabilities)
            ),
            "mean_probability": float(
                np.mean(probabilities)
            )
        })

    regions.sort(
        key=lambda x: x["max_probability"],
        reverse=True
    )

    return regions[:max_regions]


def region_to_geojson(
    region,
    crs,
    transform_obj,
    probability_map
):
    """
    Convert a detected pixel region into a GeoJSON polygon.

    Uses the bounding box of the connected region.
    """

    rows = region["rows"]
    cols = region["cols"]

    min_row = int(np.min(rows))
    max_row = int(np.max(rows))

    min_col = int(np.min(cols))
    max_col = int(np.max(cols))

    corners = [
        (min_row, min_col),
        (min_row, max_col),
        (max_row, max_col),
        (max_row, min_col),
        (min_row, min_col)
    ]

    coordinates = []

    for row, col in corners:

        lat, lon = pixel_to_latlon(
            row,
            col,
            crs,
            transform_obj
        )

        coordinates.append([
            lon,
            lat
        ])

    center_lat, center_lon = pixel_to_latlon(
        region["center_row"],
        region["center_col"],
        crs,
        transform_obj
    )

    properties = {
        "region_id": region["region_id"],
        "latitude": center_lat,
        "longitude": center_lon,
        "max_probability": region[
            "max_probability"
        ],
        "mean_probability": region[
            "mean_probability"
        ],
        "affected_pixels": region[
            "pixel_count"
        ]
    }

    return {
        "type": "Feature",
        "geometry": {
            "type": "Polygon",
            "coordinates": [
                coordinates
            ]
        },
        "properties": properties
    }


def probability_map_to_geojson(
    probability_map,
    threshold=0.5,
    min_pixels=20,
    max_regions=100
):
    """
    Complete probability-map → GeoJSON conversion.
    """

    metadata = load_satellite_georeference()

    crs, transform_obj = (
        get_geotransform_from_metadata(
            metadata
        )
    )

    regions = probability_to_regions(
        probability_map,
        threshold=threshold,
        min_pixels=min_pixels,
        max_regions=max_regions
    )

    features = []
    region_data = []

    for region in regions:

        feature = region_to_geojson(
            region,
            crs,
            transform_obj,
            probability_map
        )

        features.append(feature)

        region_data.append(
            feature["properties"]
        )

    return {
        "type": "FeatureCollection",
        "features": features
    }, region_data